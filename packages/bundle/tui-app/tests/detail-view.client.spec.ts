/** Long documents remain navigable independently of terminal scrollback. */
import { expect, it, vi } from 'vitest'
import { stripVTControlCharacters } from 'node:util'
import { DetailView } from '../src/detail-view.ts'
import { TerminalLocale } from '../src/locale.ts'

it('pages, searches literal text, and clamps offsets after resize', () => {
  let rows = 14
  const close = vi.fn()
  const reader = new DetailView('Output', Array.from({ length: 30 }, (_, i) => `row ${i}`).join('\n'), () => rows, new TerminalLocale(), close)
  const render = (): string => reader.render(40).map(line => stripVTControlCharacters(line).trimEnd()).join('\n')
  expect(render()).toContain('row 0\nrow 1\nrow 2\nrow 3')
  reader.handleInput('\x1b[6~')
  expect(render()).toContain('row 4\nrow 5')
  reader.handleInput('/')
  reader.handleInput('row 25')
  reader.handleInput('\r')
  expect(render()).toContain('row 25')
  reader.handleInput('\x1b[F')
  render()
  rows = 40
  expect(render()).toContain('row 0')
  reader.handleInput('\x1b')
  expect(close).toHaveBeenCalledOnce()
})

it('isolates language selection and strips control sequences in document text', () => {
  const zh = new TerminalLocale('zh')
  const en = new TerminalLocale()
  const reader = new DetailView('详情', 'safe\x1b[2Jtext', () => 20, zh, () => {})
  expect(reader.render(100).map(line => stripVTControlCharacters(line).trimEnd()).join('\n')).toContain('safetext')
  expect(reader.render(100).map(line => stripVTControlCharacters(line).trimEnd()).join('\n')).toContain('搜索')
  expect(en.text('Output')).toBe('Output')
})

it('scrolls with every reading key, wraps between matches in both directions, and cancels a search', () => {
  const close = vi.fn()
  const text = Array.from({ length: 40 }, (_, i) => (i % 10 === 3 ? `match ${i}` : `line ${i}`)).join('\n')
  const reader = new DetailView('Doc', text, () => 15, new TerminalLocale(), close)
  const screen = (): string => reader.render(60).map(line => stripVTControlCharacters(line).trimEnd()).join('\n')
  const first = (): string => screen().split('\n')[1] ?? ''
  screen()
  reader.handleInput('n')
  expect(first()).toBe('line 0')
  reader.handleInput('\x1b[B')
  expect(first()).toBe('line 1')
  reader.handleInput('\x1b[A')
  expect(first()).toBe('line 0')
  reader.handleInput(' ')
  expect(first()).toBe('line 5')
  reader.handleInput('\x1b[5~')
  expect(first()).toBe('line 0')
  reader.handleInput('\x1b[F')
  expect(first()).toBe('line 35')
  reader.handleInput('\x1b[H')
  expect(first()).toBe('line 0')
  reader.handleInput('x')
  expect(first()).toBe('line 0')
  reader.handleInput('/')
  reader.handleInput('match')
  expect(screen()).toContain('match')
  reader.handleInput('\r')
  expect(first()).toBe('match 3')
  expect(screen()).toContain('1/4 · match')
  reader.handleInput('N')
  expect(first()).toBe('match 33')
  reader.handleInput('n')
  expect(first()).toBe('match 3')
  reader.handleInput('/')
  reader.handleInput('zzz')
  reader.handleInput('\x1b')
  expect(screen()).toContain('No matches')
  reader.handleInput('N')
  expect(close).not.toHaveBeenCalled()
  reader.handleInput('\r')
  expect(close).toHaveBeenCalledOnce()
})

it('renders Markdown documents and starts a backward search at the last match', () => {
  const reader = new DetailView('Doc', '# Heading\n\nSome **bold** text\n\nmore text', () => 30, new TerminalLocale(), () => {}, true)
  reader.invalidate()
  const screen = (): string => reader.render(60).map(line => stripVTControlCharacters(line).trimEnd()).join('\n')
  expect(screen()).toContain('Heading')
  expect(screen()).not.toContain('**bold**')
  reader.handleInput('/')
  reader.handleInput('text')
  reader.handleInput('\x1b')
  reader.handleInput('N')
  expect(screen()).toContain('2/2 · text')
})
